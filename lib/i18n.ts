// Traducciones para Divine Tables (en/es) — Mary atiende clientas de EEUU y
// Latinoamérica, así que tanto la página de creación como la vista del
// álbum (donde suben fotos los invitados) tienen selector de idioma. Vívido
// NO usa nada de este archivo: sigue siempre en español, tal cual estaba.
//
// Patrón: cada componente que puede mostrarse en Divine Tables recibe un
// prop opcional `lang` (por defecto 'es', que es EXACTAMENTE el texto que ya
// existía) y busca sus textos acá. Si `lang` nunca se pasa (como en todas las
// páginas de Vívido), el comportamiento es idéntico al de antes.

export type Lang = 'es' | 'en';

export const LANG_STORAGE_KEY = 'event-album:lang';

export function getStoredLang(): Lang {
  if (typeof window === 'undefined') return 'es';
  try {
    return window.localStorage.getItem(LANG_STORAGE_KEY) === 'en' ? 'en' : 'es';
  } catch {
    return 'es';
  }
}

export function setStoredLang(lang: Lang) {
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // localStorage puede fallar (modo privado, etc.) — no es crítico, el
    // selector simplemente no recuerda la preferencia entre visitas.
  }
}

export function formatDateForLang(iso: string | null, lang: Lang) {
  if (!iso) return null;
  return new Date(iso).toLocaleDateString(lang === 'en' ? 'en-US' : 'es-AR', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
}

